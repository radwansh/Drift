import * as XLSX from "xlsx";
import type { AnnualSummary } from "@saas/payroll-core";
import { CATEGORY_LABELS, MONEY_CATEGORIES, type Category } from "@saas/payroll-core";

/**
 * Excel export of the annual dashboard (step 42).
 *
 * Owners take these numbers to a board and an auditor, so the workbook must
 * carry the same figures as the screen and say what each one covers. Built as a
 * pure function over the computed summary — the same object the page renders —
 * so "Excel totals equal the screen" is a property that can be tested rather
 * than eyeballed.
 */

export interface AnnualWorkbookMeta {
  companyName: string;
  generatedAt: Date;
  generatedBy: string;
}

type Row = (string | number | null)[];

function sheet(rows: Row[]): XLSX.WorkSheet {
  return XLSX.utils.aoa_to_sheet(rows);
}

function summarySheet(s: AnnualSummary, meta: AnnualWorkbookMeta): XLSX.WorkSheet {
  const rows: Row[] = [
    ["Annual payroll summary"],
    ["Company", meta.companyName],
    ["Year", s.year],
    ["Currency", s.currency],
    ["Cadence", s.periodType],
    ["Forecast method", s.forecastMethod],
    ["Periods uploaded", s.coverage.uploaded],
    ["Periods expected", s.coverage.expected],
    ["Periods estimated", s.coverage.estimatedLabels.length],
    ["Missing periods", s.missingLabels.join(", ") || "none"],
    ["Generated at", meta.generatedAt.toISOString()],
    ["Generated by", meta.generatedBy],
    [],
    ["Gross to net", "To date", "Forecast", "Full year"],
    ["Gross", s.bridge.actual.gross, s.bridge.forecast.gross, s.bridge.fullYear.gross],
    [
      "Earnings not categorised",
      s.bridge.actual.earningsBalance,
      s.bridge.forecast.earningsBalance,
      s.bridge.fullYear.earningsBalance,
    ],
    [
      "Employee deductions",
      s.bridge.actual.employeeDeductions,
      s.bridge.forecast.employeeDeductions,
      s.bridge.fullYear.employeeDeductions,
    ],
    ["Unreconciled balance", s.bridge.actual.balance, s.bridge.forecast.balance, s.bridge.fullYear.balance],
    ["Net", s.bridge.actual.net, s.bridge.forecast.net, s.bridge.fullYear.net],
    [
      "Employer costs",
      s.bridge.actual.employerCosts,
      s.bridge.forecast.employerCosts,
      s.bridge.fullYear.employerCosts,
    ],
    [
      "Total employment cost",
      s.bridge.actual.totalEmploymentCost,
      s.bridge.forecast.totalEmploymentCost,
      s.bridge.fullYear.totalEmploymentCost,
    ],
    [],
    ["Headcount (latest)", s.periods.filter((p) => p.kind === "actual").at(-1)?.headcount ?? null],
    ["Average headcount to date", s.avgHeadcountYtd],
    ["Joiners", s.headcount.joinerTotal],
    ["Leavers", s.headcount.leaverTotal],
    ["Turnover %", s.headcount.turnoverRate],
    ["Annualised turnover %", s.headcount.annualisedTurnoverRate],
  ];
  return sheet(rows);
}

function periodsSheet(s: AnnualSummary): XLSX.WorkSheet {
  const rows: Row[] = [
    ["Period", "Status", "Gross", "Net", "Employer costs", "Total employment cost", "Headcount", "Joiners", "Leavers"],
    ...s.periods.map<Row>((p) => [
      p.label,
      p.kind,
      p.gross,
      p.net,
      p.employerCosts,
      p.totalEmploymentCost,
      p.headcount,
      p.joiners,
      p.leavers,
    ]),
    [
      "Total",
      "",
      s.periods.reduce((a, p) => a + p.gross, 0),
      s.periods.reduce((a, p) => a + p.net, 0),
      s.periods.reduce((a, p) => a + p.employerCosts, 0),
      s.periods.reduce((a, p) => a + p.totalEmploymentCost, 0),
      null,
      null,
      null,
    ],
  ];
  return sheet(rows);
}

function categoriesSheet(s: AnnualSummary): XLSX.WorkSheet {
  const rows: Row[] = [
    ["Category", "To date", "Forecast", "Full year", "% of gross"],
    ...MONEY_CATEGORIES.map<Row>((category) => {
      const toDate = s.categories.byCategory[category as Category] ?? 0;
      return [
        CATEGORY_LABELS[category as Category],
        toDate,
        s.categoryForecast[category as Category] ?? 0,
        s.categoryFullYear[category as Category] ?? 0,
        s.bridge.actual.gross !== 0 ? (toDate / s.bridge.actual.gross) * 100 : null,
      ];
    }),
    [],
    ["Quantities (not money)", "To date"],
    ["Absence days", s.quantities.absence_days ?? 0],
    ["Other quantities", s.quantities.other_quantity ?? 0],
    [],
    ["Uncategorised components", "To date"],
    ...s.categories.uncategorisedKeys.map<Row>((key) => [
      key,
      s.categories.byKey[key]?.total ?? 0,
    ]),
  ];
  return sheet(rows);
}

function componentsSheet(s: AnnualSummary): XLSX.WorkSheet {
  const entries = Object.entries(s.categories.byKey).sort(
    (a, b) => Math.abs(b[1].total) - Math.abs(a[1].total),
  );
  const rows: Row[] = [
    ["Component", "Resolved category", "Total to date"],
    ...entries.map<Row>(([key, v]) => [key, CATEGORY_LABELS[v.category], v.total]),
  ];
  return sheet(rows);
}

function departmentsSheet(s: AnnualSummary): XLSX.WorkSheet {
  const rows: Row[] = [
    ["Department", "Average headcount", "To date", "Full year", "Share %", "Cost per head", "Absence days", "Absence amount"],
    ...s.departments.map<Row>((d) => [
      d.department,
      d.avgHeadcount,
      d.actual,
      d.forecast,
      d.shareOfTotal,
      d.costPerHead,
      d.absencesDays,
      d.absencesAmount,
    ]),
    [
      "Total",
      s.departments.reduce((a, d) => a + d.avgHeadcount, 0),
      s.departments.reduce((a, d) => a + d.actual, 0),
      s.departments.reduce((a, d) => a + d.forecast, 0),
      null,
      null,
      s.departments.reduce((a, d) => a + d.absencesDays, 0),
      s.departments.reduce((a, d) => a + d.absencesAmount, 0),
    ],
  ];
  return sheet(rows);
}

function yearOnYearSheet(s: AnnualSummary): XLSX.WorkSheet {
  const rows: Row[] = [
    ["Year on year", "This year", "Last year", "Change %"],
    ["Gross (like for like)", s.yoy.current.gross, s.yoy.previous.gross, s.yoy.changePct.gross],
    ["Net (like for like)", s.yoy.current.net, s.yoy.previous.net, s.yoy.changePct.net],
    [
      "Employer cost (like for like)",
      s.yoy.current.employerCost,
      s.yoy.previous.employerCost,
      s.yoy.changePct.employerCost,
    ],
    ["Average headcount", s.yoy.current.headcount, s.yoy.previous.headcount, s.yoy.changePct.headcount],
    ["Cost per head", s.yoy.current.costPerHead, s.yoy.previous.costPerHead, s.yoy.changePct.costPerHead],
    ["Comparable periods", s.yoy.comparablePeriods],
    ["Last year complete", s.yoy.previousYearComplete ? "yes" : "no"],
    ["Forecast vs last full year %", s.yoy.forecastVsLastYearPct],
    [],
    ["Period", "This year gross", "Last year gross"],
    ...s.yoy.slotPairs.map<Row>((p) => [p.label, p.currentGross, p.previousGross]),
  ];
  return sheet(rows);
}

function dataQualitySheet(s: AnnualSummary): XLSX.WorkSheet {
  const rows: Row[] = [
    ["Code", "Severity", "Title", "Detail", "Items"],
    ...s.warnings.map<Row>((w) => [w.code, w.severity, w.title, w.detail, w.items.join(", ")]),
    [],
    ["Assumptions"],
    ...s.assumptions.map<Row>((a) => [a]),
  ];
  return sheet(rows);
}

/** Builds the workbook. Returns the raw bytes, base64-encoded for transport. */
export function buildAnnualWorkbook(summary: AnnualSummary, meta: AnnualWorkbookMeta): string {
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, summarySheet(summary, meta), "Summary");
  XLSX.utils.book_append_sheet(wb, periodsSheet(summary), "Periods");
  XLSX.utils.book_append_sheet(wb, categoriesSheet(summary), "Categories");
  XLSX.utils.book_append_sheet(wb, componentsSheet(summary), "Components");
  if (summary.departments.length > 0) {
    XLSX.utils.book_append_sheet(wb, departmentsSheet(summary), "Departments");
  }
  if (summary.yoy.available) {
    XLSX.utils.book_append_sheet(wb, yearOnYearSheet(summary), "Year on year");
  }
  XLSX.utils.book_append_sheet(wb, dataQualitySheet(summary), "Data quality");

  return XLSX.write(wb, { type: "base64", bookType: "xlsx" });
}

/** The sheet names a caller can expect, for tests and for the UI's description. */
export function annualWorkbookSheets(summary: AnnualSummary): string[] {
  const names = ["Summary", "Periods", "Categories", "Components"];
  if (summary.departments.length > 0) names.push("Departments");
  if (summary.yoy.available) names.push("Year on year");
  names.push("Data quality");
  return names;
}
